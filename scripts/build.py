"""Build every graphic in assets/ and write README.md from scripts/README.template.md.

    python scripts/build.py             # fetch live GitHub data (needs the `gh` CLI, or GH_TOKEN in CI), then build
    python scripts/build.py --offline   # rebuild from data/stats.json without touching the network

Each graphic is one SVG holding a dark and a light rendering; a media query inside the file shows the one that matches the viewer
(see merge.py). Template tag:  {{pic name|alt text|width}}  ->  <img src="assets/name.svg?v=<content hash>">.

The ?v= is not decoration. The file names never change, GitHub serves them with max-age=300 through its own CDN, and the
daily refresh rewrites the same paths — so without a content-keyed query string a returning visitor keeps the stale image
and a redesign looks like it never shipped. The hash changes only when the bytes do, so unchanged graphics stay cached.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import background  # noqa: E402
import cards  # noqa: E402
import data  # noqa: E402
import hero  # noqa: E402
import parts  # noqa: E402
from merge import merge_themes  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
DIVIDERS = [("projects", "01", "Projects", "click a card"),
            ("background", "02", "Background", "courses · stack · hackathons"),
            ("activity", "03", "Activity", "refreshed daily"),
            ("contact", "04", "Say hi", "")]
BUTTONS = [("linkedin", "LinkedIn", "primary"), ("email", "Email", "secondary")]
BUTTON_W = {}


def emit(name, make):
    """Write assets/<name>.svg from make(theme) -> an svg string, merging the dark and light renderings."""
    (ASSETS / f"{name}.svg").write_text(merge_themes(make("dark"), make("light")), encoding="utf-8")


def build_assets(stats):
    for old in ASSETS.glob("*.svg"):      # the SVGs are all generated, so drop stale ones (a removed card, a renamed divider)
        old.unlink()
    emit("hero", hero.hero)
    emit("background", background.background)
    for key, no, title, note in DIVIDERS:
        emit(f"div-{key}", lambda th, no=no, title=title, note=note: parts.divider(th, no, title, note))
    for c in cards.CARDS:
        emit(f"card-{c['key']}", lambda th, c=c: cards.card(th, c))
    emit("activity", lambda th: parts.activity(th, stats))
    for key, label, kind in BUTTONS:
        BUTTON_W[key] = parts.button("dark", label, kind)[1:]
        emit(f"btn-{key}", lambda th, label=label, kind=kind: parts.button(th, label, kind)[0])


def asset_version(name):
    """Short content hash, so an image URL changes exactly when the image does."""
    return hashlib.md5((ASSETS / f"{name}.svg").read_bytes()).hexdigest()[:8]


def image(name, alt, width=None):
    w = f' width="{width}"' if width else ""
    return f'<img alt="{alt}" src="assets/{name}.svg?v={asset_version(name)}"{w}>'


def build_readme():
    tpl = (ROOT / "scripts" / "README.template.md").read_text(encoding="utf-8")

    def sub(m):
        name, alt, width = m.group(1), m.group(2), (m.group(3) or None)
        if name.startswith("btn-"):
            return image(name, alt, width or BUTTON_W[name[4:]][0])
        return image(name, alt, width)

    out = re.sub(r"\{\{pic ([a-z0-9-]+)\|([^|}]*)(?:\|([^}]*))?\}\}", sub, tpl)
    (ROOT / "README.md").write_text(out, encoding="utf-8", newline="\n")
    build_preview(out)


PREVIEW = """<!doctype html><meta charset="utf-8"><title>README preview</title>
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/github-markdown-css@5.5.1/github-markdown.css">
<style>body{{margin:0;padding:24px}}
.wrap{{max-width:830px;margin:0 auto;padding:24px 28px;border:1px solid #8884;border-radius:8px}}
@media (prefers-color-scheme:dark){{body{{background:#0d1117}}}}</style>
<!-- generated by scripts/build.py from README.md - do not edit by hand -->
<div class="wrap"><article class="markdown-body">
{body}
</article></div>
"""


def build_preview(readme: str):
    """A local stand-in for how GitHub renders the README, so the layout can be checked without pushing."""
    (ROOT / "preview-readme.html").write_text(PREVIEW.format(body=readme), encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true", help="use data/stats.json instead of calling GitHub")
    a = ap.parse_args()
    ASSETS.mkdir(exist_ok=True)
    stats = data.load(offline=a.offline)
    build_assets(stats)
    build_readme()
    n = len(list(ASSETS.glob("*.svg")))
    kb = sum(p.stat().st_size for p in ASSETS.glob("*.svg")) // 1024
    print(f"built {n} svgs ({kb} KB) and README.md · {stats['total']} contributions, {stats['commits']} commits, "
          f"{stats['prs']} PRs, {stats['issues']} issues opened, {stats['open_issues']} open")


if __name__ == "__main__":
    main()
